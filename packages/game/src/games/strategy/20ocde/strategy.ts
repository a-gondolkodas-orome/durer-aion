const oOutcomes = new Map(Object.entries(generatedOOutcomes));
const oCanonicalPositions = new Map<string, OPosition>();
const oPermutationOrders = new Map<number, number[][]>();

function oPositionKey(position: OPosition): string {
  return JSON.stringify([position.rows, position.columns]);
}

function compareONumbers(a: number[], b: number[]): number {
  for (let i = 0; i < a.length; i++) {
    if (a[i] !== b[i]) return a[i] - b[i];
  }
  return 0;
}

function oPermutations(size: number): number[][] {
  const saved = oPermutationOrders.get(size);
  if (saved) return saved;
  const orders: number[][] = [];
  const visit = (order: number[]) => {
    if (order.length === size) orders.push(order);
    else {
      for (let i = 0; i < size; i++) {
        if (!order.includes(i)) visit([...order, i]);
      }
    }
  };
  visit([]);
  oPermutationOrders.set(size, orders);
  return orders;
}

function transposeOPosition({ rows, columns }: OPosition): OPosition {
  return {
    rows: columns.map((privateCount, c) => [privateCount,
      rows.reduce((mask, row, r) => mask | (row[1] & (1 << c) ? 1 << r : 0), 0)]),
    columns: rows.map(([privateCount]) => privateCount),
  };
}

function compareOPositions(a: OPosition, b: OPosition): number {
  return compareONumbers([...a.rows.flat(), ...a.columns], [...b.rows.flat(), ...b.columns]);
}

function orientOPosition({ rows, columns }: OPosition): OPosition {
  const signatures = columns.map((privateCount, c) => [privateCount,
    rows.filter(([, mask]) => mask & (1 << c)).length]);
  let best: OPosition | undefined;
  for (const order of oPermutations(columns.length)) {
    if (order.some((c, i) => i > 0 && compareONumbers(signatures[order[i - 1]], signatures[c]) > 0)) continue;
    const candidate: OPosition = {
      rows: rows.map(([privateCount, mask]): [number, number] => [privateCount,
        order.reduce((result, c, i) => result | (mask & (1 << c) ? 1 << i : 0), 0)])
        .sort(compareONumbers),
      columns: order.map(c => columns[c]),
    };
    if (!best || compareOPositions(candidate, best) < 0) best = candidate;
  }
  if (!best) throw new Error('Cannot canonicalize O position');
  return best;
}

function canonicalOPosition(position: OPosition): OPosition {
  const key = oPositionKey(position);
  const saved = oCanonicalPositions.get(key);
  if (saved) return saved;
  let result: OPosition;
  if (position.rows.length < position.columns.length) {
    result = canonicalOPosition(transposeOPosition(position));
  } else {
    result = orientOPosition(position);
    if (position.rows.length === position.columns.length && position.rows.length > 0) {
      const transposed = orientOPosition(transposeOPosition(position));
      if (compareOPositions(transposed, result) < 0) result = transposed;
    }
  }
  oCanonicalPositions.set(key, result);
  return result;
}

function boardToOPosition(cells: MyGameState['cells']): OPosition {
  const indices = Array.from({ length: BOARD_SIZE }, (_, i) => i);
  const rows = indices.filter(r => indices.every(c => cells[r * BOARD_SIZE + c] !== 'O'));
  const columns = indices.filter(c => indices.every(r => cells[r * BOARD_SIZE + c] !== 'O'));
  return canonicalOPosition({
    rows: rows.map(r => [
      indices.filter(c => !columns.includes(c) && cells[r * BOARD_SIZE + c] === null).length,
      columns.reduce((mask, c, i) => mask | (cells[r * BOARD_SIZE + c] === null ? 1 << i : 0), 0),
    ]),
    columns: columns.map(c => indices.filter(r => !rows.includes(r) && cells[r * BOARD_SIZE + c] === null).length),
  });
}

function oLineSizes({ rows, columns }: OPosition): number[] {
  return [
    ...rows.map(([privateCount, mask]) => privateCount
      + columns.filter((_, c) => mask & (1 << c)).length),
    ...columns.map((privateCount, c) => privateCount
      + rows.filter(([, mask]) => mask & (1 << c)).length),
  ];
}

function oSquares({ rows, columns }: OPosition): [number, number][] {
  const squares: [number, number][] = [];
  rows.forEach(([privateCount, mask], r) => {
    if (privateCount > 0) squares.push([r, -1]);
    columns.forEach((_, c) => {
      if (mask & (1 << c)) squares.push([r, c]);
    });
  });
  columns.forEach((privateCount, c) => {
    if (privateCount > 0) squares.push([-1, c]);
  });
  return squares;
}

function placeInOPosition(position: OPosition, [r, c]: [number, number], isO: boolean): OPosition {
  if (!isO) {
    const rows = position.rows.map(([privateCount, mask]): [number, number] => [privateCount, mask]);
    const columns = [...position.columns];
    if (r < 0) columns[c]--;
    else if (c < 0) rows[r][0]--;
    else rows[r][1] &= ~(1 << c);
    return canonicalOPosition({ rows, columns });
  }
  return canonicalOPosition({
    rows: position.rows.filter((_, i) => i !== r).map(([privateCount, mask]): [number, number] => c < 0
      ? [privateCount, mask]
      : [privateCount + Number(Boolean(mask & (1 << c))),
        (mask & ((1 << c) - 1)) | ((mask >> (c + 1)) << c)]),
    columns: position.columns.map((privateCount, j) => privateCount
      + Number(r >= 0 && Boolean(position.rows[r][1] & (1 << j)))).filter((_, j) => j !== c),
  });
}

function solveOPosition(position: OPosition, isO: boolean): boolean {
  const key = (isO ? 'O' : 'X') + oPositionKey(position);
  const saved = oOutcomes.get(key);
  if (saved !== undefined) return saved;
  const sizes = oLineSizes(position);
  let wins: boolean;
  if (sizes.length === 0) wins = true;
  else if (sizes.includes(0)) wins = false;
  else if (!isO && Math.min(...sizes) <= 2) wins = false;
  else if (isO) {
    const urgent = sizes.flatMap((size, i) => size <= 2 ? [i] : []);
    wins = oSquares(position).some(([r, c]) => urgent.every(i => i === r
      || (c >= 0 && i === position.rows.length + c))
      && solveOPosition(placeInOPosition(position, [r, c], true), false));
  } else {
    wins = true;
    const seen = new Set<string>();
    search: for (const first of oSquares(position)) {
      const afterFirst = placeInOPosition(position, first, false);
      for (const second of oSquares(afterFirst)) {
        const after = placeInOPosition(afterFirst, second, false);
        const childKey = oPositionKey(after);
        if (seen.has(childKey)) continue;
        seen.add(childKey);
        if (!solveOPosition(after, true)) {
          wins = false;
          break search;
        }
      }
    }
  }
  oOutcomes.set(key, wins);
  return wins;
}

function fallbackStrategyForO(state: GameState): StrategyResult {
  const moves = possibleMoves(state.G, state.ctx);
  if (moves.length === 0) throw new Error('No legal move in 20ocde');
  // A line containing O is already blocked, regardless of its number of Xs.
  const uncoveredLines = lines.filter(line => line.every(index => state.G.cells[index] !== 'O'));
  const pairPriorities = [[2, 2], [2, 1], [1, 1], [2, 0], [1, 0], [0, 0]];
  const priorities = moves.map(({ args: [[index]] }) => {
    const counts = uncoveredLines.filter(line => line.includes(index))
      .map(line => line.filter(cell => state.G.cells[cell] === 'X').length)
      .sort((a, b) => b - a);
    const blockedThreats = counts.filter(count => count >= 3).length;
    // Missing (already O-blocked) lines count as zero. Immediate threats are
    // ranked separately; cap them at two only for the pair tie-breaker.
    const [first = 0, second = 0] = counts.map(count => Math.min(count, 2));
    const pairPriority = pairPriorities.length
      - pairPriorities.findIndex(([a, b]) => a === first && b === second);
    // Block the most immediate threats, then use the pair order, then prefer
    // O-free perpendicular lines. At most two lines contribute to the last tier.
    return blockedThreats * (pairPriorities.length + 1) * 3 + pairPriority * 3 + counts.length;
  });
  const highestPriority = Math.max(...priorities);
  const bestMoves = moves.filter((_, index) => priorities[index] === highestPriority);
  const selected = bestMoves[Math.floor(Math.random() * bestMoves.length)];
  return [selected.args, selected.move];
}

const lines = Array.from({ length: BOARD_SIZE }, (_, i) => [
  Array.from({ length: BOARD_SIZE }, (_, j) => i * BOARD_SIZE + j),
  Array.from({ length: BOARD_SIZE }, (_, j) => j * BOARD_SIZE + i),
]).flat();

export function winningStrategyForX(state: GameState): StrategyResult {
  const { cells } = state.G;
  const countX = (indices: number[]) => indices.filter(index => cells[index] === 'X').length;
  const empty = (indices: number[]) => indices.filter(index => cells[index] === null);
  const clearLines = lines.filter(line => line.every(index => cells[index] !== 'O'));
  const numberOfX = cells.filter(cell => cell === 'X').length;
  const place = (indices: number[]): StrategyResult => [[indices], 'placeMarks'];

  // Take an immediate win before building the next shape.
  for (const line of clearLines) {
    const remaining = empty(line);
    if (remaining.length > 0 && remaining.length <= 2) return place(remaining);
  }

  if (numberOfX === 0) {
    // Both Xs, and the opening O when present, occupy distinct rows and columns.
    const openings = possibleMoves(state.G, state.ctx).filter(({ args: [indices] }) => {
      const occupied = [...indices, ...cells.flatMap((cell, index) => cell === 'O' ? [index] : [])];
      return new Set(occupied.map(index => Math.floor(index / BOARD_SIZE))).size === occupied.length
        && new Set(occupied.map(index => index % BOARD_SIZE)).size === occupied.length;
    });
    if (openings.length > 0) {
      const selected = openings[Math.floor(Math.random() * openings.length)];
      return [selected.args, selected.move];
    }
  }

  if (numberOfX === 2) {
    // Complete the L, then extend its main line to three Xs to form a T.
    // Keep the stem and the perpendicular line through the new tip free of Os.
    const singleLines = clearLines.filter(line => countX(line) === 1);
    for (const main of singleLines) {
      for (const stem of singleLines) {
        if (main === stem) continue;
        const corner = main.find(index => stem.includes(index));
        if (corner === undefined || cells[corner] !== null) continue;
        const tip = main.find(index => index !== corner && cells[index] === null
          && clearLines.some(line => line !== main && line.includes(index)));
        if (tip !== undefined) return place([corner, tip]);
      }
    }
  }

  if (numberOfX === 4) {
    // O blocked the three-X line. Complete a rectangle off that line, making
    // the stem a new three-X threat and keeping the other two sides clear.
    for (const main of lines.filter(line => countX(line) === 3)) {
      for (const stem of clearLines.filter(line => countX(line) === 2)) {
        const corner = main.find(index => stem.includes(index));
        if (corner === undefined || cells[corner] !== 'X') continue;
        for (const side of clearLines.filter(line => countX(line) === 1)) {
          const tip = main.find(index => side.includes(index));
          if (tip === undefined || cells[tip] !== 'X') continue;
          for (const opposite of clearLines) {
            const first = stem.find(index => opposite.includes(index));
            const second = side.find(index => opposite.includes(index));
            if (first !== undefined && second !== undefined && first !== second
              && cells[first] === null && cells[second] === null) return place([first, second]);
          }
        }
      }
    }
  }

  if (numberOfX === 6) {
    // O blocked the new threat. Extend both remaining clear sides to three Xs.
    // Their intersection must already be X, so one O cannot block both threats.
    const pairs = clearLines.filter(line => countX(line) === 2);
    for (const first of pairs) {
      for (const second of pairs) {
        const corner = first.find(index => second.includes(index));
        if (first !== second && corner !== undefined && cells[corner] === 'X') {
          return place([empty(first)[0], empty(second)[0]]);
        }
      }
    }
  }

  // Positions outside this opening sequence still need a legal move.
  return randomStrategy(state);
}

export function winningStrategy(state: GameState): StrategyResult {
  return markForPlayer(state.G, state.ctx.currentPlayer) === 'O'
    ? winningStrategyForO(state)
    : winningStrategyForX(state);
}

export function strategyWrapper(category: Category) {
  return (state: GameState, _botID: string): StrategyResult => {
    if (state.ctx.phase === 'startNewGame') return [[startingPosition(category)], 'setStartingPosition'];
    return state.G.difficulty === 'test' ? randomStrategy(state) : winningStrategy(state);
  };
}
